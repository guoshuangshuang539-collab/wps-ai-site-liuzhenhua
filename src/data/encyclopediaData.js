export function resolveEncyclopediaLocale(locale) {
  const normalized = `${locale || ''}`.toLowerCase()
  if (normalized.startsWith('zh')) {
    return 'zh'
  }
  if (normalized && encyclopediaEntriesByLocale[normalized]) {
    return normalized
  }
  return 'en'
}
